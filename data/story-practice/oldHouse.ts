export const oldHousePractice: OldHouseChapterPractice[] = writtenPractice.map(
  (practice, chapter) => ({
    ...practice,
    words: practice.words.map((word, index) => ({
      ...word,
      waray: OLD_HOUSE_WARAY?.words[chapter][index] ?? "",
    })),
  }),
);

const capitalize = (value: string) =>
  value.charAt(0).toUpperCase() + value.slice(1);

// Options are kept in this order here; the practice screen shuffles them
// on every attempt (shuffleOptions below).
const choices = (word: OldHouseWord) => [
  capitalize(word.english),
  ...word.distractors.map(capitalize),
];

export function buildOldHouseQuestions(
  practice: OldHouseChapterPractice,
  dialect: OldHouseDialect,
): StoryPracticeQuestion[] {
  const [a, b, c, d, speak, translate1, fill1, translate2, fill2] =
    practice.words;

  const card = (id: number, word: OldHouseWord): StoryPracticeQuestion => ({
    id,
    type: "card_match",
    word: word[dialect],
    correctMeaning: capitalize(word.english),
    options: choices(word),
  });
  const translate = (id: number, word: OldHouseWord): StoryPracticeQuestion => ({
    id,
    type: "multiple_choice",
    word: word[dialect],
    correctMeaning: capitalize(word.english),
    options: choices(word),
  });
  const fill = (id: number, word: OldHouseWord): StoryPracticeQuestion => ({
    id,
    type: "fill_blank",
    meaning: word[dialect],
    correctWord: word.english,
    acceptedAnswers: word.acceptedAnswers,
  });

  return [
    card(1, a),
    card(2, b),
    card(3, c),
    card(4, d),
    { id: 5, type: "speak", word: speak[dialect], micOptional: true },
    translate(6, translate1),
    fill(7, fill1),
    translate(8, translate2),
    fill(9, fill2),
    {
      id: 10,
      type: "expression",
      prompt: practice.showIt.prompt,
      expectedExpression: practice.showIt.expectedExpression,
      countsAsCompleted: true,
    },
  ];
}

// Pass mark: 7 of 10. Q10 always counts once it is attempted or skipped.
export const OLD_HOUSE_REQUIRED_CORRECT = 7;

export const oldHouseStoryPracticeChapters: StoryPracticeChapter[] =
  (OLD_HOUSE_DIALECTS as OldHouseDialect[]).flatMap((dialect) =>
    oldHousePractice.map((practice) => ({
      dialect,
      chapter: practice.chapter,
      lessonId: `story_${dialect}_oldhouse_${practice.chapter}`,
      questions: buildOldHouseQuestions(practice, dialect),
      requiredCorrect: OLD_HOUSE_REQUIRED_CORRECT,
      shuffleOptions: true,
    })),
  );
